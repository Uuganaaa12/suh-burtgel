import re

_MAX_RAW_LENGTH = 20

# Монгол кирилл цагаан толгойн 35 том үсэг (Ё, Ө, Ү орно).
_PLATE_RE = re.compile(
    r" *([0-9]{4}) *([АБВГДЕЁЖЗИЙКЛМНОӨПРСТУҮФХЦЧШЩЪЫЬЭЮЯ]{3}) *"
)


def normalize_plate(raw: str) -> str:
    """Улсын дугаарыг шалгаад нэг хэлбэрт («0123 УБА») оруулна.

    Зөвшөөрөгдөх оролт: эхэн, төгсгөл болон цифр, үсгийн хооронд
    хэдэн ч ASCII хоосон зай байж болно (огт байхгүй байж бас болно),
    кирилл үсэг жижиг ч байж болно.

    Цифр нь зөвхөн ASCII 0-9 байна (``\\d`` биш), үсэг нь зөвхөн монгол
    кирилл үсэг байна. Ингэснээр латин «A», «K», «M» гэх мэт адилхан
    харагддаг үсэг, бүтэн өргөнтэй «０», араб-энэтхэг «٠» зэрэг цифр
    татгалзагдаж, UNIQUE баганад нэг дугаар хоёр өөр бичлэгээр орохоос
    сэргийлнэ. Unicode NFKC нормчлолыг санаатайгаар хэрэглээгүй:
    тэр нь «０»-г «0» болгож хүлээн авах байсан.

    Args:
        raw: Оршин суугчийн оруулсан улсын дугаар.

    Returns:
        «DDDD ҮҮҮ» хэлбэрийн дугаар, жишээ нь «0123 УБА».

    Raises:
        TypeError: ``raw`` нь str биш бол.
        ValueError: Оролт хэт урт, эсвэл хэлбэр буруу бол.
    """
    if not isinstance(raw, str):
        raise TypeError(
            f"Улсын дугаар текст (str) байх ёстой, "
            f"{type(raw).__name__} төрөл ирлээ."
        )

    if len(raw) > _MAX_RAW_LENGTH:
        raise ValueError(
            f"Улсын дугаар {_MAX_RAW_LENGTH} тэмдэгтээс урт байж болохгүй."
        )

    match = _PLATE_RE.fullmatch(raw.upper())
    if match is None:
        if any(ch.isascii() and ch.isalpha() for ch in raw):
            raise ValueError(
                "Улсын дугаарт латин үсэг орсон байна. "
                "Зөвхөн кирилл үсэг ашиглана уу."
            )
        if any(ch.isdigit() and not ch.isascii() for ch in raw):
            raise ValueError(
                "Улсын дугаарт стандарт бус цифр орсон байна. "
                "Зөвхөн 0-9 цифр ашиглана уу."
            )
        raise ValueError(
            "Улсын дугаарын хэлбэр буруу байна. "
            "4 цифр, 3 кирилл үсэгтэй байх ёстой, жишээ нь «0123 УБА»."
        )

    digits, letters = match.groups()
    return f"{digits} {letters}"
